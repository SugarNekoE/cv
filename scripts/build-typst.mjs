import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const projectRoot = resolve(import.meta.dirname, '..');
const sourcePath = resolve(projectRoot, 'src/contents/CV_en.md');
const outputDirectory = resolve(projectRoot, 'build/typst');
const typstPath = resolve(outputDirectory, 'CV_en.typ');
const pdfPath = resolve(outputDirectory, 'CV_en.pdf');

function escapeText(text) {
  return text.replace(/[\\#$\[\]_`*~@]/g, '\\$&');
}

function escapeString(text) {
  return text.replaceAll('\\', '\\\\').replaceAll('"', '\\"');
}

function renderInline(text, sourceLine) {
  if (/(?:`|\*\*|__|!\[)/.test(text)) {
    throw new Error(`Unsupported inline Markdown: ${sourceLine}`);
  }

  const tokens = /\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)|~~([^~]+)~~/g;
  let rendered = '';
  let cursor = 0;

  for (const match of text.matchAll(tokens)) {
    rendered += escapeText(text.slice(cursor, match.index));

    if (match[2]) {
      rendered += `#link("${escapeString(match[2])}")[${escapeText(match[1])}]`;
    } else {
      rendered += `#strike[${escapeText(match[3])}]`;
    }

    cursor = match.index + match[0].length;
  }

  return rendered + escapeText(text.slice(cursor));
}

function renderMarkdown(markdown) {
  const lines = markdown.split(/\r?\n/);
  const output = [
    '// Generated from src/contents/CV_en.md by scripts/build-typst.mjs.',
    '// Do not edit this file; run `corepack pnpm build:typst` instead.',
    '#import "/src/typst/resume.typ": contact-grid, resume',
    '',
    '#show: resume',
    '',
  ];
  let inPersonalInformation = false;

  for (let index = 0; index < lines.length;) {
    const line = lines[index];

    if (line.trim() === '') {
      index += 1;
      continue;
    }

    if (line === '---') {
      index += 1;
      continue;
    }

    const heading = /^(#{1,3})[ \t]+(.+?)\s*$/.exec(line);
    if (heading) {
      const level = heading[1].length;
      const title = heading[2];

      output.push(`${'='.repeat(level)} ${renderInline(title, line)}`, '');
      inPersonalInformation = level === 2 && title === 'Personal Information';
      index += 1;
      continue;
    }

    if (/^(?:#{4,6}[ \t]|>[ \t]|\d+[.)][ \t]|[*+][ \t]|\s+\S|```)/.test(line)) {
      throw new Error(`Unsupported block Markdown: ${line}`);
    }

    if (line.startsWith('- ')) {
      const items = [];

      while (index < lines.length && lines[index].startsWith('- ')) {
        items.push(lines[index].slice(2));
        index += 1;
      }

      if (inPersonalInformation) {
        const facts = items.map(item => {
          const separator = item.indexOf(': ');

          if (separator === -1) {
            throw new Error(`Personal information item has no label: ${item}`);
          }

          const label = item.slice(0, separator + 1);
          const value = item.slice(separator + 2);

          return `  ([${escapeText(label)}], [${renderInline(value, item)}]),`;
        });

        output.push('#contact-grid((', ...facts, '))', '');
      } else {
        output.push(...items.map(item => `- ${renderInline(item, item)}`), '');
      }

      continue;
    }

    output.push(renderInline(line, line), '');
    index += 1;
  }

  return `${output.join('\n')}\n`;
}

const markdown = await readFile(sourcePath, 'utf8');
await mkdir(outputDirectory, { recursive: true });
await writeFile(typstPath, renderMarkdown(markdown), 'utf8');

const result = spawnSync(
  'typst',
  [
    'compile',
    '--root',
    projectRoot,
    '--ignore-system-fonts',
    typstPath,
    pdfPath,
  ],
  { cwd: projectRoot, stdio: 'inherit' },
);

if (result.error) {
  throw result.error;
}

if (result.status !== 0) {
  throw new Error(`Typst failed with status ${result.status ?? result.signal}`);
}

console.log(`generated ${typstPath.slice(projectRoot.length + 1)}`);
console.log(`rendered ${pdfPath.slice(projectRoot.length + 1)}`);
